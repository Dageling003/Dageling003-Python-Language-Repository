"""
题一：会记忆的计数器（闭包 + nonlocal）
需求：写一个函数 make_counter()，调用后返回一个计数函数。
- 计数函数每被调用一次，返回值就加 1，从 1 开始（第一次调用返回 1）
- 用 make_counter() 再造第二个计数器，验证两个计数器各自独立、互不干扰
- 硬性要求：全程不许使用全局变量
自测：连续调用第一个计数器三次，输出应为 1、2、3；此时调用第二个计数器，输出应仍是 1。
"""
# 外层函数（闭包工厂）：负责创建并"记住"计数变量 a
def make_counter():
    a = 0  # a 是外层函数的局部变量，被内层函数引用后形成闭包，调用结束后不会被销毁

    # 内层函数（真正的计数器）：每次被调用就给 a 加 1
    def counter():
        nonlocal a  # 声明 a 不是自己的局部变量，而是外层作用域的变量，这样才能修改它而不是新建
        a = a + 1  # 修改外层变量 a（若不加 nonlocal，这里会报"赋值前引用"的错误）
        print(f"现在的值：{a}")

    # 返回内层函数本身（注意不要写成 counter()，那是调用函数而不是返回函数）
    return counter


# 每调用一次 make_counter()，都会生成一份独立的变量 a，两个计数器互不干扰
c1 = make_counter()  # c1 指向第一个闭包，拥有自己独立的 a
c2 = make_counter()  # c2 指向第二个闭包，拥有另一份独立的 a

c1()  # 1（c1 自己的 a：0 -> 1）
c1()  # 2（1 -> 2）
c1()  # 3（2 -> 3）
c2()  # 1（c2 的 a 从头开始，不受 c1 影响）


